GL_BASE AS (
    SELECT L.ACCOUNT, L.SUBACCOUNT, L.AMOUNTIDR, L.AMOUNT,
           L.TRANS_DATE, L.TRANS_DUEDATE, L.TRANS_CURRENT, L.TRANS_MODULE,
           L.NFAKTUR, L.DESCRIPTION, L.NSHARE, L.BRANCH, L.CURRENCY
    FROM DENPASAR.LEDGER_HISTORICAL@cammon L
    INNER JOIN DENPASAR.ACCOUNT A ON L.ACCOUNT = A.CODE
    WHERE L.TRANS_PERIOD   = TO_CHAR(TO_DATE('2026-04-21','yyyy-mm-dd'),'yyyymm')
      AND L.TRANS_CURRENT  = 0
      AND A.SUBACCOUNT_TYPE > 0
      AND L.TRANS_DUEDATE <= TO_DATE('2026-04-21','yyyy-mm-dd')
      AND L.ACCOUNT IN ('10401021','10401022','10401031','10401071')
      AND L.GEN_DATE       = TO_DATE('2026-04-21','yyyy-mm-dd')
    UNION ALL
    SELECT L.ACCOUNT, L.SUBACCOUNT, L.AMOUNTIDR, L.AMOUNT,
           L.TRANS_DATE, L.TRANS_DUEDATE, L.TRANS_CURRENT, L.TRANS_MODULE,
           L.NFAKTUR, L.DESCRIPTION, L.NSHARE, L.BRANCH, L.CURRENCY
    FROM DENPASAR.LEDGER_HISTORICAL@cammon L
    INNER JOIN DENPASAR.ACCOUNT A ON L.ACCOUNT = A.CODE
    WHERE L.ACCOUNT IN ('10401021','10401022','10401031','10401071')
      AND L.TRANS_DATE    >= TRUNC(TO_DATE('2026-04-21','yyyy-mm-dd'),'MM')
      AND L.TRANS_DUEDATE <= TO_DATE('2026-04-21','yyyy-mm-dd')
      AND L.TRANS_CURRENT  = 1
      AND A.SUBACCOUNT_TYPE > 0
      AND L.GEN_DATE       = TO_DATE('2026-04-21','yyyy-mm-dd')
),
GL_WITH_SUBACCT_NET AS (
    SELECT GB.*,
           SUM(GB.AMOUNTIDR) OVER (PARTITION BY GB.ACCOUNT, GB.SUBACCOUNT) AS SUBACCT_NET
    FROM GL_BASE GB
),
