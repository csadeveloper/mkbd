-- Klasifikasi aging rows ke HUTANG / DENDA / CUSTODY
-- Plus filter HAVING SUM per (SUBACCOUNT, COMPONENT) > 0
-- ============================================================
AGING_CLASSIFIED AS (
    SELECT
        AR.*,
        CASE
            WHEN AR.DEBIT <> 0 AND AR.TRANS_MODULE = 12
                 THEN 'DENDA'
            WHEN AR.DEBIT <> 0 AND AR.TRANS_MODULE IN (13, 15)
                 AND (AR.DESCRIPTION LIKE '%CUSTODY%'
                   OR AR.DESCRIPTION LIKE '%KUSTODI%'
                   OR AR.DESCRIPTION LIKE '%METERAI%'
                   OR AR.DESCRIPTION LIKE '%MARKET DATA%')
                 THEN 'CUSTODY'
            WHEN AR.DEBIT <> 0
                 AND (AR.TRANS_MODULE NOT IN (12, 13, 15)
                   OR (AR.TRANS_MODULE IN (13, 15) AND AR.DESCRIPTION LIKE '%DEVIDEN%')
                   OR (AR.TRANS_MODULE IN (13, 15) AND AR.DESCRIPTION LIKE '%W/O%')
                   OR (AR.TRANS_MODULE IN (13, 15) AND AR.DESCRIPTION LIKE '%IPO'))
                 THEN 'HUTANG'
            ELSE 'UNCLASSIFIED'
        END AS COMPONENT
    FROM AGING_RECEIVABLE AR
    WHERE AR.DEBIT <> 0
),
AGING_WITH_CLIENT_TOTAL AS (
