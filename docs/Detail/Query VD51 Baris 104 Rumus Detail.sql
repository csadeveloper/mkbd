        AWT.CURRENCY              AS CURRENCY,
        AWT.DEBITIDR              AS DEBITIDR,
        CAST(NULL AS NUMBER)      AS AMOUNTIDR,
        CAST(NULL AS NUMBER)      AS SUBACCT_NET,
        AWT.CLIENT_COMPONENT_TOTAL AS CLIENT_COMPONENT_TOTAL,
        CAST(NULL AS NUMBER)      AS OUTSTANDING_AMOUNT,
        CAST(NULL AS NUMBER)      AS INTEREST_AMOUNT,
        CAST(NULL AS NUMBER)      AS CUSTODY_AMOUNT,
        CAST(NULL AS NUMBER)      AS GL_SUM,
        CAST(NULL AS NUMBER)      AS TOTAL_RESULT
    FROM AGING_WITH_CLIENT_TOTAL AWT
    INNER JOIN DENPASAR.CLIENT C ON AWT.SUBACCOUNT = C.CODE
    WHERE AWT.COMPONENT IN ('HUTANG','DENDA','CUSTODY')
      AND AWT.CLIENT_COMPONENT_TOTAL > 0

    UNION ALL

    -- === Section 2: GL_SUM detail (per ledger row, hanya subaccount nett > 0) ===
    SELECT
        '2_GL_DETAIL'         AS SECTION,
        2                     AS SORT_KEY,
        'GL'                  AS COMPONENT,
        CAST(NULL AS VARCHAR2(20)) AS CLIENT_CODE,
        CAST(NULL AS VARCHAR2(100)) AS CLIENT_NAME,
        GWS.ACCOUNT           AS ACCOUNT,
        GWS.SUBACCOUNT        AS SUBACCOUNT,
        GWS.TRANS_MODULE      AS TRANS_MODULE,
        GWS.TRANS_DATE        AS TRANS_DATE,
        GWS.TRANS_DUEDATE     AS TRANS_DUEDATE,
        GWS.NFAKTUR           AS NFAKTUR,
        GWS.DESCRIPTION       AS DESCRIPTION,
        GWS.BRANCH            AS BRANCH,
        GWS.CURRENCY          AS CURRENCY,
        CAST(NULL AS NUMBER)  AS DEBITIDR,
        GWS.AMOUNTIDR         AS AMOUNTIDR,
        GWS.SUBACCT_NET       AS SUBACCT_NET,
        CAST(NULL AS NUMBER)  AS CLIENT_COMPONENT_TOTAL,
        CAST(NULL AS NUMBER)  AS OUTSTANDING_AMOUNT,
        CAST(NULL AS NUMBER)  AS INTEREST_AMOUNT,
        CAST(NULL AS NUMBER)  AS CUSTODY_AMOUNT,
        CAST(NULL AS NUMBER)  AS GL_SUM,
        CAST(NULL AS NUMBER)  AS TOTAL_RESULT
    FROM GL_WITH_SUBACCT_NET GWS
    WHERE GWS.SUBACCT_NET > 0

    UNION ALL

    -- === Section 3: SUMMARY (totals + final result) ===
    SELECT
        '3_SUMMARY'              AS SECTION,
        3                        AS SORT_KEY,
        'SUMMARY'                AS COMPONENT,
        CAST(NULL AS VARCHAR2(20)) AS CLIENT_CODE,
        CAST(NULL AS VARCHAR2(100)) AS CLIENT_NAME,
        CAST(NULL AS VARCHAR2(20)) AS ACCOUNT,
        CAST(NULL AS VARCHAR2(20)) AS SUBACCOUNT,
        CAST(NULL AS NUMBER)     AS TRANS_MODULE,
        CAST(NULL AS DATE)       AS TRANS_DATE,
        CAST(NULL AS DATE)       AS TRANS_DUEDATE,
        CAST(NULL AS VARCHAR2(20)) AS NFAKTUR,
        CAST(NULL AS VARCHAR2(255)) AS DESCRIPTION,
        CAST(NULL AS VARCHAR2(20)) AS BRANCH,
        CAST(NULL AS VARCHAR2(3))  AS CURRENCY,
        CAST(NULL AS NUMBER)     AS DEBITIDR,
        CAST(NULL AS NUMBER)     AS AMOUNTIDR,
        CAST(NULL AS NUMBER)     AS SUBACCT_NET,
        CAST(NULL AS NUMBER)     AS CLIENT_COMPONENT_TOTAL,
        CT.OUTSTANDING_AMOUNT    AS OUTSTANDING_AMOUNT,
        CT.INTEREST_AMOUNT       AS INTEREST_AMOUNT,
        CT.CUSTODY_AMOUNT        AS CUSTODY_AMOUNT,
        GT.GL_SUM                AS GL_SUM,
        (CT.INTEREST_AMOUNT + CT.CUSTODY_AMOUNT
           + (GT.GL_SUM - (CT.OUTSTANDING_AMOUNT + CT.INTEREST_AMOUNT + CT.CUSTODY_AMOUNT)))
                                 AS TOTAL_RESULT
    FROM COMPONENT_TOTALS CT
    CROSS JOIN GL_TOTAL GT
)
ORDER BY SORT_KEY, COMPONENT, CLIENT_CODE, ACCOUNT, SUBACCOUNT, TRANS_DATE;